"""3D sector mesh (blockMesh) for the nozzle jet -> deflector disk VOF case.

A 20 deg sector around the nozzle axis (x) with rotational cyclic sides, so the
swirl is kept and the sheet can break into ligaments in the circumferential
direction. Base cells are coarse (1.6 mm); the solver refines them around the
oil surface down to 0.4 mm (constant/dynamicMeshDict, 2 levels).

Region (m): x from -0.05 (gas inlet) to 0.25 (outlet), r from the axis to 0.15.
Solids left out of the mesh: the lance r < 14 mm for x < 0.082 (its orifice
r < 10 mm is the oil inlet, 1 cm in front of the disk) and the disk
r < 32.5 mm, x 0.092...0.100.
Usage: python make_mesh.py [scale] [sector_deg]   (scale > 1 refines the base mesh)
"""
import math
import sys
from pathlib import Path

S = float(sys.argv[1]) if len(sys.argv) > 1 else 1.0
SECTOR = float(sys.argv[2]) if len(sys.argv) > 2 else 20.0
H = 1.6e-3 / S                  # base cell size near the jet, the disk and the sheet

X = [-0.050, 0.082, 0.092, 0.100, 0.200, 0.250]    # gas inlet, oil inlet, disk back, disk front, end of sheet zone, outlet
R = [0.0, 0.010, 0.014, 0.0325, 0.150]              # axis, orifice, lance, disk rim, outer
# cell size at the ends of each interval (m)
DX = [(5e-3 / S, H), (H, H), (H, H), (H, H), (H, 4e-3 / S)]
DR = [(H, H), (H, H), (H, H), (H, H)]
# blocks that exist: (x interval, r interval)
BLOCKS = [(0, 2), (0, 3),
          (1, 0), (1, 1), (1, 2), (1, 3),
          (2, 3),
          (3, 0), (3, 1), (3, 2), (3, 3),
          (4, 0), (4, 1), (4, 2), (4, 3)]
# cells around the axis: base size at r = 0.1 m
NT = max(4, round(math.radians(SECTOR) * 0.1 / H))


def cells(L, d0, d1):
    if abs(d1 - d0) < 1e-12:
        return max(1, round(L / d0)), 1.0
    return max(1, round(L * math.log(d1 / d0) / (d1 - d0))), d1 / d0


nx = [cells(X[i + 1] - X[i], *DX[i]) for i in range(len(X) - 1)]
nr = [cells(R[j + 1] - R[j], *DR[j]) for j in range(len(R) - 1)]

t = math.radians(SECTOR / 2)
verts, vid = [], {}


def v(i, j, side):          # side -1 back, +1 front; axis points shared (collapsed hexes -> prisms)
    key = (i, j, 0 if R[j] == 0 else side)
    if key not in vid:
        r = R[j]
        vid[key] = len(verts)
        verts.append((X[i], r * math.cos(t), side * r * math.sin(t) if r else 0.0))
    return vid[key]


blocks, ncell = [], 0
for i, j in BLOCKS:
    hexv = [v(i, j, -1), v(i + 1, j, -1), v(i + 1, j + 1, -1), v(i, j + 1, -1),
            v(i, j, 1), v(i + 1, j, 1), v(i + 1, j + 1, 1), v(i, j + 1, 1)]
    (n1, g1), (n2, g2) = nx[i], nr[j]
    blocks.append(f"    hex ({' '.join(map(str, hexv))}) ({n1} {n2} {NT}) simpleGrading ({g1:.5g} {g2:.5g} 1)")
    ncell += n1 * n2 * NT

# circumferential edges are arcs
edges, done = [], set()
for i, j in BLOCKS:
    for ii in (i, i + 1):
        for jj in (j, j + 1):
            if R[jj] > 0 and (ii, jj) not in done:
                done.add((ii, jj))
                edges.append(f"    arc {v(ii, jj, -1)} {v(ii, jj, 1)} ({X[ii]:.15g} {R[jj]:.15g} 0)")


def face_x(i, j):           # face at x = X[i] spanning r interval j
    return [v(i, j, -1), v(i, j + 1, -1), v(i, j + 1, 1), v(i, j, 1)]


def face_r(i, j):           # face at r = R[j] spanning x interval i
    return [v(i, j, -1), v(i, j, 1), v(i + 1, j, 1), v(i + 1, j, -1)]


nX = len(X) - 1
patches = {
    "gasInlet": ("patch", [face_x(0, 2), face_x(0, 3)]),
    "oilInlet": ("patch", [face_x(1, 0)]),
    "nozzle": ("wall", [face_x(1, 1), face_r(0, 2)]),
    "disk": ("wall", [face_x(2, 0), face_x(2, 1), face_x(2, 2),
                      face_x(3, 0), face_x(3, 1), face_x(3, 2), face_r(2, 3)]),
    "outlet": ("patch", [face_x(nX, j) for j in range(4)]),
    "outer": ("wall", [face_r(i, 4) for i in range(nX)]),
}
front, back = [], []
for i, j in BLOCKS:
    back.append([v(i, j, -1), v(i, j + 1, -1), v(i + 1, j + 1, -1), v(i + 1, j, -1)])
    front.append([v(i, j, 1), v(i + 1, j, 1), v(i + 1, j + 1, 1), v(i, j + 1, 1)])

out = ["FoamFile { format ascii; class dictionary; object blockMeshDict; }",
       f"// generated by make_mesh.py, scale {S}, sector {SECTOR} deg, base cells {H * 1e3:.2f} mm, {ncell} cells",
       "convertToMeters 1;",
       "defaultPatch { name axis; type empty; }    // collapsed faces on the axis: none left",
       "vertices", "("]
out += [f"    ({x:.15g} {y:.15g} {z:.15g}) // {n}" for n, (x, y, z) in enumerate(verts)]
out += [");", "blocks", "("] + blocks + [");", "edges", "("] + edges + [");", "boundary", "("]
for name, (typ, faces) in patches.items():
    out += [f"    {name}", "    {", f"        type {typ};", "        faces", "        ("]
    out += [f"            ({' '.join(map(str, f))})" for f in faces]
    out += ["        );", "    }"]
for name, nb, faces in (("back", "front", back), ("front", "back", front)):
    out += [f"    {name}", "    {", "        type cyclic;", f"        neighbourPatch {nb};",
            "        transformType rotational;", "        rotationAxis (1 0 0);",
            "        rotationCentre (0 0 0);", "        faces", "        ("]
    out += [f"            ({' '.join(map(str, f))})" for f in faces]
    out += ["        );", "    }"]
out += [");"]
(Path(__file__).parent / "system" / "blockMeshDict").write_text("\n".join(out) + "\n")
print(f"blockMeshDict: {len(BLOCKS)} blocks, {ncell} cells, sector {SECTOR} deg, "
      f"{NT} cells around, base cells {H * 1e3:.2f} mm")
