"""Background mesh (blockMesh) for the nozzle with a central stem and three struts.

A 120 deg sector (one strut) around the nozzle axis x with rotational cyclic
sides: the whole nozzle is three such sectors. The mesh starts at the stem
surface r = 5 mm, so there are no needle cells at the axis. Polar cells, 3.2 mm;
block edges lie on the lance, orifice and disk radii and faces, so snappyHexMesh
(which cuts the lance, disk and strut and refines to 0.4 mm) only snaps to the strut.

Inner boundary r = 5 mm:  stem (wall) up to the disk; behind the disk the same
cylinder continues as a slip surface ("axis") - a small simplification of the wake.
Usage: python make_mesh.py
"""
import math
from pathlib import Path

SECTOR = 120.0
H = 3.2e-3                                           # base cell size

X = [-0.050, 0.082, 0.092, 0.100, 0.250]             # gas inlet, oil exit, disk back, disk front, outlet
R = [0.005, 0.0112, 0.014, 0.0325, 0.150]            # stem, orifice (annulus D22.4/10), lance, disk rim, outer
NT = round(math.radians(SECTOR) * 0.1 / H)           # cells around: base size at r = 0.1 m


def n(L):
    return max(1, round(L / H))


nx = [n(X[i + 1] - X[i]) for i in range(len(X) - 1)]
nr = [n(R[j + 1] - R[j]) for j in range(len(R) - 1)]
t = math.radians(SECTOR / 2)
verts, vid = [], {}


def v(i, j, side):                                   # side -1 back, +1 front
    key = (i, j, side)
    if key not in vid:
        vid[key] = len(verts)
        verts.append((X[i], R[j] * math.cos(t), side * R[j] * math.sin(t)))
    return vid[key]


blocks, edges, ncell = [], [], 0
for i in range(len(nx)):
    for j in range(len(nr)):
        hexv = [v(i, j, -1), v(i + 1, j, -1), v(i + 1, j + 1, -1), v(i, j + 1, -1),
                v(i, j, 1), v(i + 1, j, 1), v(i + 1, j + 1, 1), v(i, j + 1, 1)]
        blocks.append(f"    hex ({' '.join(map(str, hexv))}) ({nx[i]} {nr[j]} {NT}) simpleGrading (1 1 1)")
        ncell += nx[i] * nr[j] * NT
for i in range(len(X)):
    for j in range(len(R)):
        edges.append(f"    arc {v(i, j, -1)} {v(i, j, 1)} ({X[i]:.15g} {R[j]:.15g} 0)")


def face_x(i, j):
    return [v(i, j, -1), v(i, j + 1, -1), v(i, j + 1, 1), v(i, j, 1)]


def face_r(i, j):
    return [v(i, j, -1), v(i, j, 1), v(i + 1, j, 1), v(i + 1, j, -1)]


nX, nR = len(X) - 1, len(R) - 1
patches = {
    "gasInlet": ("patch", [face_x(0, j) for j in range(nR)]),
    "outlet": ("patch", [face_x(nX, j) for j in range(nR)]),
    "outer": ("wall", [face_r(i, nR) for i in range(nX)]),
    "stem": ("wall", [face_r(i, 0) for i in range(3)]),          # up to the disk front face
    "axis": ("wall", [face_r(i, 0) for i in range(3, nX)]),      # behind the disk: slip in the fields
}
back = [[v(i, j, -1), v(i, j + 1, -1), v(i + 1, j + 1, -1), v(i + 1, j, -1)] for i in range(nX) for j in range(nR)]
front = [[v(i, j, 1), v(i + 1, j, 1), v(i + 1, j + 1, 1), v(i, j + 1, 1)] for i in range(nX) for j in range(nR)]

out = ["FoamFile { format ascii; class dictionary; object blockMeshDict; }",
       f"// generated by make_mesh.py: sector {SECTOR} deg, {NT} cells around, base {H * 1e3:.1f} mm, {ncell} cells",
       "convertToMeters 1;", "vertices", "("]
out += [f"    ({x:.15g} {y:.15g} {z:.15g}) // {k}" for k, (x, y, z) in enumerate(verts)]
out += [");", "blocks", "("] + blocks + [");", "edges", "("] + edges + [");", "boundary", "("]
for name, (typ, faces) in patches.items():
    out += [f"    {name}", "    {", f"        type {typ};", "        faces", "        ("]
    out += [f"            ({' '.join(map(str, f))})" for f in faces]
    out += ["        );", "    }"]
for name, nb, faces in (("back", "front", back), ("front", "back", front)):
    out += [f"    {name}", "    {", "        type cyclic;", f"        neighbourPatch {nb};",
            "        transformType rotational;", "        rotationAxis (1 0 0);",
            "        rotationCentre (0 0 0);", "        faces", "        ("]
    out += [f"            ({' '.join(map(str, f))})" for f in faces]
    out += ["        );", "    }"]
out += [");"]
(Path(__file__).resolve().parent / "system" / "blockMeshDict").write_text("\n".join(out) + "\n")
print(f"blockMeshDict: sector {SECTOR} deg, {NT} cells around, {ncell} cells")
