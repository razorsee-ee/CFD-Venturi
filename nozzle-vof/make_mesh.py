"""Axisymmetric wedge mesh (blockMesh) for the nozzle jet -> deflector disk VOF case.

Region (m): x from -0.15 (gas inlet) to 0.30 (outlet), r from the axis to 0.15.
Solids left out of the mesh: nozzle body r < 14 mm for x < 0 (orifice r < 10 mm
is the oil inlet at x = 0) and the disk r < 32.5 mm, x 0.092...0.100.
Usage: python make_mesh.py [scale]   (scale > 1 refines)
"""
import math
import sys
from pathlib import Path

S = float(sys.argv[1]) if len(sys.argv) > 1 else 1.0
H = 0.4e-3 / S                  # fine cell size near the jet and the disk
WEDGE = 2.5                     # half angle, deg

X = [-0.150, 0.0, 0.092, 0.100, 0.300]      # gas inlet, nozzle exit, disk back, disk front, outlet
R = [0.0, 0.010, 0.014, 0.0325, 0.150]      # axis, orifice, nozzle body, disk rim, outer
# cell size at the ends of each interval (m)
DX = [(3e-3 / S, H), (H, H), (H, H), (H, 2e-3 / S)]
DR = [(H, H), (H, H), (H, H), (H, 2e-3 / S)]
# blocks that exist: (x interval, r interval)
BLOCKS = [(0, 2), (0, 3),
          (1, 0), (1, 1), (1, 2), (1, 3),
          (2, 3),
          (3, 0), (3, 1), (3, 2), (3, 3)]


def cells(L, d0, d1):
    if abs(d1 - d0) < 1e-12:
        return max(1, round(L / d0)), 1.0
    return max(1, round(L * math.log(d1 / d0) / (d1 - d0))), d1 / d0


nx = [cells(X[i + 1] - X[i], *DX[i]) for i in range(4)]
nr = [cells(R[j + 1] - R[j], *DR[j]) for j in range(4)]

t = math.radians(WEDGE)
verts, vid = [], {}


def v(i, j, side):          # side -1 back, +1 front; axis points shared
    key = (i, j, 0 if R[j] == 0 else side)
    if key not in vid:
        r = R[j]
        vid[key] = len(verts)
        verts.append((X[i], r * math.cos(t), side * r * math.sin(t) if r else 0.0))
    return vid[key]


blocks, ncell = [], 0
for i, j in BLOCKS:
    hexv = [v(i, j, -1), v(i + 1, j, -1), v(i + 1, j + 1, -1), v(i, j + 1, -1),
            v(i, j, 1), v(i + 1, j, 1), v(i + 1, j + 1, 1), v(i, j + 1, 1)]
    (n1, g1), (n2, g2) = nx[i], nr[j]
    blocks.append(f"    hex ({' '.join(map(str, hexv))}) ({n1} {n2} 1) simpleGrading ({g1:.5g} {g2:.5g} 1)")
    ncell += n1 * n2


def face_x(i, j):           # face at x = X[i] spanning r interval j
    return [v(i, j, -1), v(i, j + 1, -1), v(i, j + 1, 1), v(i, j, 1)]


def face_r(i, j):           # face at r = R[j] spanning x interval i
    return [v(i, j, -1), v(i, j, 1), v(i + 1, j, 1), v(i + 1, j, -1)]


patches = {
    "gasInlet": ("patch", [face_x(0, 2), face_x(0, 3)]),
    "oilInlet": ("patch", [face_x(1, 0)]),
    "nozzle": ("wall", [face_x(1, 1), face_r(0, 2)]),
    "disk": ("wall", [face_x(2, 0), face_x(2, 1), face_x(2, 2),
                      face_x(3, 0), face_x(3, 1), face_x(3, 2), face_r(2, 3)]),
    "outlet": ("patch", [face_x(4, j) for j in range(4)]),
    "outer": ("wall", [face_r(i, 4) for i in range(4)]),
    "axis": ("empty", [face_r(1, 0), face_r(3, 0)]),
}
front, back = [], []
for i, j in BLOCKS:
    back.append([v(i, j, -1), v(i, j + 1, -1), v(i + 1, j + 1, -1), v(i + 1, j, -1)])
    front.append([v(i, j, 1), v(i + 1, j, 1), v(i + 1, j + 1, 1), v(i, j + 1, 1)])
patches["front"] = ("wedge", front)
patches["back"] = ("wedge", back)

out = ["FoamFile { format ascii; class dictionary; object blockMeshDict; }",
       f"// generated by make_mesh.py, scale {S}, fine cells {H * 1e3:.2f} mm, {ncell} cells",
       "convertToMeters 1;", "vertices", "("]
out += [f"    ({x:.15g} {y:.15g} {z:.15g}) // {n}" for n, (x, y, z) in enumerate(verts)]
out += [");", "blocks", "("] + blocks + [");", "edges ();", "boundary", "("]
for name, (typ, faces) in patches.items():
    out += [f"    {name}", "    {", f"        type {typ};", "        faces", "        ("]
    out += [f"            ({' '.join(map(str, f))})" for f in faces]
    out += ["        );", "    }"]
out += [");"]
(Path(__file__).parent / "system" / "blockMeshDict").write_text("\n".join(out) + "\n")
print(f"blockMeshDict: {len(BLOCKS)} blocks, {ncell} cells, fine cells {H * 1e3:.2f} mm")
